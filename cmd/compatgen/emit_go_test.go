// The Go emitter, over the same hermetic fixture the rest of the generator's
// tests use (testdata/shapes/widgets.json + testdata/recipes/widgets.json).
// Nothing here reads the committed corpus, opens a network connection or
// compiles the emitted source; the emitted corpus is proved to compile by the
// go-sdk suite's own build.

// goldenPath is the emitted source for the fixture service. It carries a
// .golden suffix so the Go tool never treats it as part of any package: it
// imports an SDK package for a service that does not exist.
const goldenPath = "testdata/golden/scenarios_widgets_gen.go.golden"

// updateGolden rewrites the golden file instead of comparing against it:
//
//	OVERCAST_UPDATE_GOLDEN=1 go test -tags dev -run TestEmitGo ./cmd/compatgen
//
// Read the diff before committing the result — the golden file is the review
// artifact for what the emitter writes, and a golden regenerated without being
// read proves nothing.
func updateGolden() bool { return os.Getenv("OVERCAST_UPDATE_GOLDEN") == "1" }

func TestEmitGo_matchesTheGoldenSource(t *testing.T) {
	// Given: the fixture service, generated.
	_, gen := generateFixture(t)

	// When: it is emitted as Go.
	emission, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}

	// Then: byte for byte what is committed.
	if emission.Path != "compat/suites/go-sdk/internal/groups/scenarios_widgets_gen.go" {
		t.Errorf("emitted path = %s", emission.Path)
	}
	if updateGolden() {
		if err := os.MkdirAll(filepath.Dir(goldenPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(goldenPath, emission.Contents, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Fatalf("golden file rewritten; re-run without OVERCAST_UPDATE_GOLDEN and read the diff")
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read golden: %v (set OVERCAST_UPDATE_GOLDEN=1 to write it)", err)
	}
	if string(emission.Contents) != string(want) {
		t.Errorf("emitted source differs from %s; set OVERCAST_UPDATE_GOLDEN=1 to update it after reading the diff\n--- got ---\n%s", goldenPath, emission.Contents)
	}
}

func TestEmitGo_isDeterministicAndGofmtClean(t *testing.T) {
	_, gen := generateFixture(t)

	first, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	second, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	if string(first.Contents) != string(second.Contents) {
		t.Error("two emissions of one scenario differ; the byte-identical regeneration gate would fail at random")
	}
	// gofmt is applied inside emitGo, so this is the belt to that braces: it
	// proves the committed bytes are a fixed point rather than merely parseable.
	formatted, err := format.Source(first.Contents)
	if err != nil {
		t.Fatalf("emitted source does not parse: %v", err)
	}
	if string(formatted) != string(first.Contents) {
		t.Error("emitted source is not gofmt-clean")
	}
}

// TestEmitGo_emitsEveryGroupAndTest keeps the emitted registrations in step
// with the scenario. A test the emitter silently dropped would report as a
// hard failure in the suite (the generated-no-backend rule), which is loud but
// late.
func TestEmitGo_emitsEveryGroupAndTest(t *testing.T) {
	_, gen := generateFixture(t)
	emission, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	source := string(emission.Contents)
	for _, g := range gen.scenario.Groups {
		for _, tc := range g.Tests {
			key := `"` + g.Name + ":" + tc.Name + `"`
			if !strings.Contains(source, key) {
				t.Errorf("no impl registered under %s", key)
			}
			if !strings.Contains(source, "func (g *widgetsScenarios) "+goNameTestMethod(g.Name, tc.Name)+"(") {
				t.Errorf("no function emitted for %s/%s", g.Name, tc.Name)
			}
		}
		// Every group registers both hooks, even the probe group whose two
		// lists are empty: an empty phase is a no-op, not a missing one.
		for _, method := range []string{goNameSetupMethod(g.Name), goNameTeardownMethod(g.Name)} {
			if !strings.Contains(source, "func (g *widgetsScenarios) "+method+"(") {
				t.Errorf("no %s emitted for %s", method, g.Name)
			}
		}
	}
	if !strings.Contains(source, "// Code generated by cmd/compatgen; DO NOT EDIT.") {
		t.Error("the generated-file marker is missing")
	}
}

// TestEmitGo_refusesAMemberItCannotSpell pins the one refusal this backend
// introduces, and what it costs: the group leaves the go-sdk column rather
// than being emitted as a guess or dropped silently.
func TestEmitGo_refusesAMemberItCannotSpell(t *testing.T) {
	f, gen := generateFixture(t)
	_ = f

	// Given: a group whose call names a timestamp member. The fixture models
	// ListWidgets with an optional CreatedAfter, which the recipe never binds
	// — no committed scenario reaches this, because timestamps are refused
	// upstream, so the case is constructed rather than generated.
	timestamped := group{
		Name: "widgets-gen-timestamped",
		Kind: groupLifecycle,
		Tests: []test{newTest("ListWidgets", "ListWidgets", call{
			Op:     "ListWidgets",
			Params: map[string]any{"CreatedAfter": "2026-09-06T00:00:00Z"},
		}, responseField(checks("$.Widgets", isList())))},
	}
	gen.scenario.Groups = append(gen.scenario.Groups, timestamped)

	// When: the service is emitted.
	emission, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}

	// Then: the group is not in the emitted source, and the refusal names the
	// member and the reason.
	if strings.Contains(string(emission.Contents), "widgets-gen-timestamped") {
		t.Error("a group the emitter cannot spell was emitted anyway")
	}
	if !emission.Refused["widgets-gen-timestamped"] {
		t.Fatal("the refused group was not reported as unable")
	}
	if len(emission.Gaps) != 1 {
		t.Fatalf("gaps = %+v, want one", emission.Gaps)
	}
	got := emission.Gaps[0]
	if got.Reason != "go-emit-unsupported:CreatedAfter" || got.Operation != "ListWidgets" || got.Group != "widgets-gen-timestamped" {
		t.Errorf("gap = %+v", got)
	}
	if !strings.Contains(got.Detail, "timestamp") {
		t.Errorf("gap detail does not say what kind of member it was: %q", got.Detail)
	}
}

// TestBuildRegistry_scopesARefusedGroupAwayFromItsBackend is the other half of
// that refusal: `suites` is derived from backend availability, so a backend
// that cannot execute a group must not be listed against it — otherwise the
// loader's generated-no-backend rule turns the refusal into a hard failure.
func TestBuildRegistry_scopesARefusedGroupAwayFromItsBackend(t *testing.T) {
	_, gen := generateFixture(t)
	scenarios := []*scenario{gen.scenario}
	backends := []string{"cli", "go-sdk", "python-sdk"}
	refused := gen.scenario.Groups[0].Name

	reg := buildRegistry(scenarios, backends, nil, unableSuites{refused: {"go-sdk": true}})
	for _, g := range reg.Groups {
		want := backends
		if g.Name == refused {
			want = []string{"cli", "python-sdk"}
		}
		if strings.Join(g.Suites, ",") != strings.Join(want, ",") {
			t.Errorf("group %s suites = %v, want %v", g.Name, g.Suites, want)
		}
	}

	// And a group no backend can execute is left out entirely rather than
	// written with an empty `suites`, which the schema refuses.
	none := unableSuites{refused: {"cli": true, "go-sdk": true, "python-sdk": true}}
	for _, g := range buildRegistry(scenarios, backends, nil, none).Groups {
		if g.Name == refused {
			t.Error("a group no suite can execute was still registered")
		}
	}
}

// TestEmitGoIndex_isTheOnlyHandEditFreeRegistrationPoint pins both halves of
// the index: it lists what was emitted, and it still compiles when nothing was.
func TestEmitGoIndex_listsEveryEmittedServiceAndCompilesWhenEmpty(t *testing.T) {
	full, err := emitGoIndex([]string{"sqs", "organizations"})
	if err != nil {
		t.Fatal(err)
	}
	source := string(full)
	if !strings.Contains(source, "ScenariosOrganizations(c),") || !strings.Contains(source, "ScenariosSqs(c),") {
		t.Errorf("index does not name both services:\n%s", source)
	}
	if strings.Index(source, "ScenariosOrganizations") > strings.Index(source, "ScenariosSqs") {
		t.Error("the index is not sorted; regeneration would depend on recipe read order")
	}

	empty, err := emitGoIndex(nil)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(empty), "return nil") {
		t.Errorf("the empty index does not compile to an empty list:\n%s", empty)
	}
	if strings.Contains(string(empty), "c *clients.Clients") {
		t.Error("the empty index names an unused parameter, which does not compile")
	}
}

// TestGoValue_coversTheIRsValueGrammar keeps the naming table total: every form
// the IR admits has a Go expression, and nothing else does.
func TestGoValue_coversTheIRsValueGrammar(t *testing.T) {
	for _, tc := range []struct {
		name string
		in   string
		want string
	}{
		{"a string", `"hello"`, `"hello"`},
		{"a number", `30`, `30`},
		{"a boolean", `false`, `false`},
		{"null", `null`, `nil`},
		{"a list", `["a","b"]`, `[]any{"a", "b"}`},
		{"an object", `{"K":"v"}`, `map[string]any{"K": "v"}`},
		{"$name", `{"$name":"q"}`, `scenario.Name("q")`},
		{"$ref", `{"$ref":"queue.url"}`, `scenario.Ref("queue.url")`},
		{"$lit", `{"$lit":{"$weird":1}}`, `scenario.Lit(map[string]any{"$weird": 1})`},
		{"$concat", `{"$concat":["a",{"$ref":"q.u"}]}`, `scenario.Concat("a", scenario.Ref("q.u"))`},
		{"$index", `{"$index":[{"$ref":"q.urls"},1]}`, `scenario.Index(scenario.Ref("q.urls"), 1)`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var v any
			if err := decodeStrict([]byte(tc.in), &v); err != nil {
				t.Fatal(err)
			}
			got, err := goValue(v, "")
			if err != nil {
				t.Fatalf("goValue(%s): %v", tc.in, err)
			}
			if got != tc.want {
				t.Errorf("goValue(%s) = %s, want %s", tc.in, got, tc.want)
			}
		})
	}

	// A value outside the grammar has no expression, and says so rather than
	// rendering something that would not compile.
	if _, err := goValue(struct{}{}, ""); err == nil {
		t.Error("a value outside the IR's grammar was rendered")
	}
}

// TestGoValue_wrapsAWideComposite keeps a generated file reviewable: gofmt
// does not break a long literal, so the emitter does.
func TestGoValue_wrapsAWideComposite(t *testing.T) {
	var v any
	if err := json.Unmarshal([]byte(`{"AVeryLongMemberNameIndeed":"and a value long enough to pass the budget","Another":"one"}`), &v); err != nil {
		t.Fatal(err)
	}
	got, err := goValue(v, "\t")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "\n") {
		t.Errorf("a composite past the width budget stayed on one line:\n%s", got)
	}
}

// TestGoMethodNamesAreUnique refuses two names that fold to one Go identifier
// before the suite fails to build with no indication of which pair caused it.
func TestGoMethodNamesAreUnique(t *testing.T) {
	groups := []group{
		{Name: "svc-gen-a-b", Tests: []test{{Name: "C"}}},
		{Name: "svc-gen-a", Tests: []test{{Name: "BC"}}},
	}
	err := goMethodNamesAreUnique("svc", groups)
	if err == nil {
		t.Fatal("two colliding method names were accepted")
	}
	for _, want := range []string{"svc-gen-a-b/C", "svc-gen-a/BC", "testSvcGenABC"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("the collision message lacks %q: %v", want, err)
		}
	}
}

// TestExplainGoRendersTheEmittedCall is the definition-of-done item that there
// is one naming table: `-explain -lang go` must print the statements the
// emitter writes, not a second description of them.
func TestExplainGoRendersTheEmittedCall(t *testing.T) {
	_, gen := generateFixture(t)
	g, tc, ok := gen.scenario.findTest("widgets-gen-widget", "CreateWidget")
	if !ok {
		t.Fatal("fixture has no CreateWidget")
	}
	explained := renderGo(gen.scenario, g, tc)

	emission, err := emitGo(gen)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	emitted := string(emission.Contents)

	lines, err := goInputLines(goNamePackage(gen.scenario.Client.SDKID), tc.Call.Op, tc.Call.Params, "")
	if err != nil {
		t.Fatal(err)
	}
	if len(lines) < 2 {
		t.Fatalf("CreateWidget renders %d line(s); the fixture no longer exercises member binding", len(lines))
	}
	for _, line := range lines {
		if !strings.Contains(explained, line) {
			t.Errorf("-explain -lang go does not render %q:\n%s", line, explained)
		}
		if !strings.Contains(emitted, line) {
			t.Errorf("the emitted source does not contain %q", line)
		}
	}
}
